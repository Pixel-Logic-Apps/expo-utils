/**
 * Rótulos da interface da Play Store usados pelo tutorial de avaliação.
 *
 * IMPORTANTE: estas strings NÃO são do app — são rótulos de propriedade do Google que o
 * usuário vai procurar na tela dele. Traduzir por conta própria faz o tutorial mandar o
 * usuário procurar um rótulo que não existe.
 *
 * As tabelas abaixo foram EXTRAÍDAS do APK da Play Store, não traduzidas à mão. Procedimento
 * (o mesmo para atualizar quando o Google mudar um rótulo):
 *
 *   # 1. um emulador com Play Store (tag google_apis_playstore)
 *   emulator -avd <AVD> -no-window &
 *   # 2. o APK universal do system image traz TODOS os locales de uma vez;
 *   #    o /data/app/.../base.apk instalado só traz o idioma do aparelho.
 *   adb pull /product/priv-app/Phonesky/Phonesky.apk .
 *   # 3. dump dos recursos (IDs são estáveis entre locales dentro do mesmo APK)
 *   $ANDROID_HOME/build-tools/36.0.0/aapt2 dump resources Phonesky.apk > all.txt
 *
 * Em `all.txt` cada recurso aparece como `resource 0x<id> string/...` seguido de uma linha
 * `(<config>) "valor"` por idioma — `()` é o default (inglês). Os nomes vêm ofuscados, então
 * ache o ID pelo valor em inglês e leia os outros idiomas nesse mesmo ID. Os IDs usados estão
 * anotados em cada grupo abaixo; eles mudam a cada build do Phonesky, reconfira pelo texto.
 *
 * CINCO rótulos não existem no APK porque a Play os recebe do backend: as quatro abas da home
 * (`tabForYou`, `tabTrending`, `tabWorkApps`, `tabKids`) e `tabPosted`. Esses continuam em
 * pt/en/es (conferidos em tela) e caem no inglês nos demais idiomas — são decoração, nenhuma
 * seta do tutorial aponta para eles. Se for conferir um desses numa tela real, atualize aqui.
 *
 * `sampleReview` é texto NOSSO (o comentário que o usuário "digita"), não do Google.
 *
 * Locales sem entrada caem em `en` via getPlayLabels(). O conjunto é o mesmo da tabela
 * TRANSLATIONS de utils/ask-for-review.tsx (31 idiomas).
 */

export interface PlayLabels {
    /** Nome do app da loja no launcher. 0x7f1409f0 */
    playStore: string;
    /** Abas da home da Play Store. Servidas pelo backend — não estão no APK. */
    tabForYou: string;
    tabTrending: string;
    tabWorkApps: string;
    tabKids: string;
    /** Bottom sheet da conta. 0x7f140df5 / 0x7f140c8b / 0x7f140d49 / 0x7f140eb8 / 0x7f140fc3 / 0x7f140fc1 / 0x7f140c6a */
    manageAccount: string;
    manageAppsDevices: string;
    notificationsOffers: string;
    paymentsSubscriptions: string;
    playProtect: string;
    playPoints: string;
    library: string;
    /** Tela "Gerenciar apps e dispositivos". 0x7f140c6f / 0x7f140c76 / 0x7f140cc9+0x7f140837 / 0x7f140c88 / 0x7f140c86 / 0x7f140c4c */
    updateAll: string;
    seeDetails: string;
    storageUsed: string;
    syncApps: string;
    noDeviceSynced: string;
    ratingsReviews: string;
    /** Tela "Avaliações". 0x7f140c9c / 0x7f140d1e / 0x7f1410a9 / 0x7f1410a8 / 0x7f1416cb */
    reviewsTitle: string;
    tabNotRated: string;
    /** Servido pelo backend — não está no APK. */
    tabPosted: string;
    sendFeedback: string;
    privateFeedback: string;
    fromYourLibrary: string;
    /** Composer de avaliação. 0x7f141032 / 0x7f1416b8 / 0x7f1416be / 0x7f1410ae */
    post: string;
    privacyNotice: string;
    learnMore: string;
    describeExperience: string;
    /** Texto de exemplo digitado no campo. NOSSO, não do Google. */
    sampleReview: string;
    /**
     * Nome do usuário quando o app não passa `userName`. NOSSO, não do Google — no aparelho
     * real aparece o nome da Conta do Google. Usado no composer e para a inicial do avatar.
     */
    defaultUserName: string;
}

